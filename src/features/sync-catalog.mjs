// ---------------------------------------------------------------------------
// Copies the app's feature catalog into the website, English only.
//
//   node src/features/sync-catalog.mjs [path/to/evenus/docs/features.json]
//
// The app repo is the source of truth (docs/features.json is generated there
// from src/lib/features/catalog.ts). The website cannot read it at deploy time,
// because Vercel only checks out this repo, so the fields the feature pages
// quote are copied here and committed as src/features/catalog.json.
//
// ⚠️ Re-run this whenever the app's catalog changes. The build fails if a
// catalogued feature has no page in src/features/content/, so a new feature in
// the app cannot silently go missing from the site.
// ---------------------------------------------------------------------------
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = process.argv[2] || join(here, '../../../evenus/docs/features.json');
const f = JSON.parse(readFileSync(src, 'utf8'));

// Em dashes are refused by the website build, and the app copy has a few.
// (The old "a eight-character code" typo was fixed in the app in fix round 14.)
const clean = (s) => (typeof s === 'string' ? s.replace(/\s*—\s*/g, ', ') : s);
const deep = (v) => (Array.isArray(v) ? v.map(deep) : clean(v));

// "Where to find it" comes from the app too (its guide shows the same path,
// built from the app's own tab, section and row labels), so the site and the
// app can never disagree. A feature without one stops the sync.
const missing = f.features.filter((x) => !x.en?.where || !Array.isArray(x.en?.whereParts) || !x.en.whereParts.length).map((x) => x.id);
if (missing.length) throw new Error(`features.json has no en.where / en.whereParts for: ${missing.join(', ')}`);

const out = {
  source: 'evenus/docs/features.json (generated from src/lib/features/catalog.ts). English only. Do not edit by hand: run node src/features/sync-catalog.mjs.',
  groups: f.groups.map((g) => ({ id: g.id, title: g.title.en, features: g.features })),
  features: f.features.map((x) => ({
    id: x.id,
    group: x.group,
    pro: Boolean(x.pro),
    platforms: x.platforms,
    currencies: x.currencies,
    inAppRoute: x.inAppRoute,
    addedInVersion: x.addedInVersion,
    related: x.related,
    keywords: x.keywords.en,
    title: clean(x.en.title),
    oneLiner: clean(x.en.oneLiner),
    whoFor: clean(x.en.whoFor),
    steps: deep(x.en.steps),
    tips: deep(x.en.tips),
    partnerSees: clean(x.en.partnerSees),
    countryNotes: clean(x.en.countryNotes),
    where: clean(x.en.where),
    whereParts: deep(x.en.whereParts),
  })),
};
writeFileSync(join(here, 'catalog.json'), JSON.stringify(out, null, 1) + '\n');

// where.json is generated from the same export, never edited by hand. The
// build reads it and fails if a catalogued feature has no path, and
// featurepages.mjs refuses to render if it has drifted from catalog.json.
const where = {
  _about: 'Generated by node src/features/sync-catalog.mjs from the app\'s docs/features.json (en.where, the same "Where to find it" path the in-app guide shows). Do not edit by hand.',
};
for (const x of out.features) where[x.id] = x.where;
writeFileSync(join(here, 'where.json'), JSON.stringify(where, null, 1) + '\n');
console.log(`catalog.json: ${out.features.length} features in ${out.groups.length} groups; where.json: ${out.features.length} paths`);
